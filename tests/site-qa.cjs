const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  fs.mkdirSync('qa-output', { recursive: true });
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const results = [];
  for (const width of [1440, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    await page.goto('file://' + path.resolve('docs/index.html'));
    await page.locator('.hero-figure img').waitFor();
    await page.evaluate(async()=>{await Promise.all([...document.images].filter(i=>i.getAttribute('src')).map(i=>{i.loading='eager';return i.decode()}))});
    const sizes = await page.evaluate(() => ({ viewport: innerWidth, scroll: document.documentElement.scrollWidth, images:[...document.images].filter(i=>!i.closest('dialog')).every(i=>i.complete&&i.naturalWidth>0) }));
    await page.screenshot({ path: `qa-output/draft-${width}.png`, fullPage: true });
    await page.screenshot({ path: `qa-output/hero-${width}.png`, fullPage: false });
    if (sizes.scroll > sizes.viewport) throw Error(`Horizontal overflow at ${width}: ${sizes.scroll}`);
    if (!sizes.images) throw Error(`Missing image at ${width}`);
    await page.getByRole('tab', { name: 'Software progress' }).click();
    if (!((await page.locator('#demo-title').textContent()).includes('Progress'))) throw Error('Tab click failed');
    await page.getByRole('tab', { name: 'Software progress' }).press('ArrowRight');
    if (!((await page.locator('#demo-title').textContent()).includes('options'))) throw Error('Keyboard tab failed');
    await page.getByRole('button', {name:'Expand scanner research workbench image'}).click();
    if (!(await page.locator('dialog').isVisible())) throw Error('Image expansion failed');
    await page.keyboard.press('Escape');
    if (await page.locator('dialog').isVisible()) throw Error('Image Escape close failed');
    await page.getByRole('button', {name:'Expand scanner research workbench image'}).click();
    await page.getByRole('button', {name:'Close enlarged image'}).click();
    if (await page.locator('dialog').isVisible()) throw Error('Image Close button failed');
    await page.getByText('How much will it cost?', { exact: true }).click();
    if ((await page.locator('details').last().getAttribute('open')) === null) throw Error('FAQ failed');
    await page.getByText('How much will it cost?', { exact: true }).click();
    if ((await page.locator('details').last().getAttribute('open')) !== null) throw Error('FAQ close failed');
    await page.locator('#continuity').screenshot({path: `qa-output/continuity-${width}.png`});
    await page.getByRole('button', {name:'Expand greenhouse location test'}).click();
    if (!(await page.locator('dialog').isVisible())) throw Error('Greenhouse expansion failed');
    await page.keyboard.press('Escape');
    results.push({ width, overflow: false, images: 'loaded', tabs: 'passed', keyboard: 'passed', imageDialog: 'passed', faq: 'passed' });
  }
  for (const width of [1440,390,320]) {
    await page.setViewportSize({width,height:900});
    await page.goto('file://' + path.resolve('docs/motion-lab.html'));
    await page.evaluate(async()=>Promise.all([...document.images].map(i=>i.decode())));
    if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)) throw Error('Motion overflow '+width);
    await page.getByRole('button',{name:'Greenhouse',exact:true}).click();
    if(await page.locator('#b').getAttribute('aria-hidden')!=='false') throw Error('Scene switch failed');
    await page.getByRole('button',{name:'Pause ambient motion'}).click();
    if(await page.locator('#pause').getAttribute('aria-pressed')!=='true') throw Error('Pause failed');
    await page.getByRole('button',{name:'Inspect the ingredients'}).click();
    if(!(await page.locator('#details').isVisible())) throw Error('Disclosure failed');
    await page.screenshot({path:'qa-output/motion-'+width+'.png',fullPage:true});
    await page.emulateMedia({reducedMotion:'reduce'});
    if(await page.locator('.glow').evaluate(e=>getComputedStyle(e).animationName)!=='none') throw Error('Reduced motion failed');
    await page.emulateMedia({reducedMotion:'no-preference'});
    results.push({width,motionLab:'passed'});
  }
  if (errors.length) throw Error(errors.join('\n'));
  fs.writeFileSync('qa-output/results.json', JSON.stringify({ results, pageErrors: errors, source: 'checked-out docs/index.html' }, null, 2));
  console.log(JSON.stringify(results));
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
